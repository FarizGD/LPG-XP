using System.Security.Cryptography;
using System.Text;
using LPGXP.Archive;

static int Usage()
{
    Console.WriteLine("""
    LPG-XP | FXPENC v1
      keygen <key-file> [--csharp <output.cs>]
      pack <input-directory> <output.fxpenc> <key-file>
      list <input.fxpenc> <key-file>
      extract <input.fxpenc> <output-directory> <key-file>

    Key files contain a raw 32-byte AES-256 key. Keep them private.
    """);
    return 2;
}

static byte[] LoadKey(string path)
{
    byte[] key = File.ReadAllBytes(path);
    if (key.Length != 32) throw new InvalidDataException("Key file must contain exactly 32 bytes.");
    return key;
}

static void WriteEmbeddedKey(string path, byte[] key)
{
    string hex = Convert.ToHexString(key);
    string source = $$"""
    // Generated by LPG-XP FXPENC. Do not commit this file to a public repository.
    namespace LPGXP.Generated;

    internal static class GameArchiveKey
    {
        internal static byte[] GetKey() => System.Convert.FromHexString("{{hex}}");
    }
    """;
    string? parent = Path.GetDirectoryName(Path.GetFullPath(path));
    if (!string.IsNullOrEmpty(parent)) Directory.CreateDirectory(parent);
    File.WriteAllText(path, source + Environment.NewLine, new UTF8Encoding(false));
}

try
{
    if (args.Length == 0) return Usage();
    switch (args[0].ToLowerInvariant())
    {
        case "keygen":
        {
            if (args.Length != 2 && args.Length != 4) return Usage();
            if (args.Length == 4 && args[2] != "--csharp") return Usage();
            byte[] key = FxpencArchive.GenerateKey();
            try
            {
                string? parent = Path.GetDirectoryName(Path.GetFullPath(args[1]));
                if (!string.IsNullOrEmpty(parent)) Directory.CreateDirectory(parent);
                File.WriteAllBytes(args[1], key);
                if (args.Length == 4) WriteEmbeddedKey(args[3], key);
            }
            finally { CryptographicOperations.ZeroMemory(key); }
            Console.WriteLine($"Generated private key file: {args[1]}");
            if (args.Length == 4) Console.WriteLine($"Generated embedded-key source: {args[3]}");
            Console.WriteLine("Keep both files out of public source control.");
            return 0;
        }
        case "pack":
        {
            if (args.Length != 4) return Usage();
            byte[] key = LoadKey(args[3]);
            try { FxpencArchive.PackDirectory(args[1], args[2], key); }
            finally { CryptographicOperations.ZeroMemory(key); }
            Console.WriteLine($"Packed {args[1]} -> {args[2]}");
            return 0;
        }
        case "list":
        {
            if (args.Length != 3) return Usage();
            byte[] key = LoadKey(args[2]);
            try
            {
                foreach (var entry in FxpencArchive.List(args[1], key))
                    Console.WriteLine($"{entry.Length,12} bytes  {entry.Path}");
            }
            finally { CryptographicOperations.ZeroMemory(key); }
            return 0;
        }
        case "extract":
        {
            if (args.Length != 4) return Usage();
            byte[] key = LoadKey(args[3]);
            try { FxpencArchive.ExtractDirectory(args[1], args[2], key); }
            finally { CryptographicOperations.ZeroMemory(key); }
            Console.WriteLine($"Extracted {args[1]} -> {args[2]}");
            return 0;
        }
        default:
            return Usage();
    }
}
catch (Exception ex)
{
    Console.Error.WriteLine($"LPG-XP FXPENC ERROR: {ex.GetType().Name}: {ex.Message}");
    return 1;
}
